enum class AppLanguage(val code: String, val isRtl: Boolean) {
  AR("ar", true),
  EN("en", false);

  companion object {
    fun fromCode(code: String): AppLanguage = entries.firstOrNull { it.code == code } ?: AR
  }
}

enum class AppThemeMode(val id: String) {
  DARK("dark"),
  LIGHT("light"),
  SYSTEM("system");

  companion object {
    fun fromId(id: String): AppThemeMode = entries.firstOrNull { it.id == id } ?: DARK
  }
}

